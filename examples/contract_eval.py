"""Evaluate an agent against a declarative BehaviorContract.

What this shows:
- A `BehaviorContract` describes what your agent MUST do (output shape,
  budget limits, content constraints). `to_graders()` auto-generates a
  matching `CodeGrader` for each section — no grader glue on your side.
- `SimpleAdapter` wraps a plain async function as an agent.
- The generated graders each carry their own policy (GATE vs WARN vs
  TRACK); `CompositeGrader` honors that when aggregating.

For a version that also checks tool-call behavior, you need a custom
adapter that translates your agent's tool calls into
`Transcript.tool_calls` — that's orthogonal to the contract itself.

Run: `python examples/contract_eval.py`

Expected output (abridged):
    Graders auto-generated from contract: 3
      planner-v1.json_schema       (policy=gate)
      planner-v1.token_budget      (policy=warn)
      planner-v1.contains          (policy=track)

    tracelens: 2 tasks, 4 trials, pass_rate=100.0%, mean_score=1.0000, ...
"""

import asyncio

from tracelens import (
    BehaviorContract,
    CompositeGrader,
    EvalSet,
    EvaluationRunner,
    ReportGenerator,
    RunnerConfig,
    SimpleAdapter,
    Task,
)


async def planner_agent(input_data: dict) -> dict:
    goal = input_data.get("goal", "")
    return {
        "result": f"Plan for: {goal}",
        "disclaimer": "This plan is generated by an AI and should be reviewed.",
    }


async def main() -> None:
    contract = BehaviorContract(
        contract_id="planner-v1",
        version="1.0.0",
        output_schema={
            "type": "object",
            "properties": {
                "result": {"type": "string"},
                "disclaimer": {"type": "string"},
            },
            "required": ["result", "disclaimer"],
        },
        max_tokens=5000,              # Soft budget — WARN.
        must_include=["AI"],          # The disclaimer mentions "AI" — TRACK.
    )

    grader_pairs = contract.to_graders()
    print(f"Graders auto-generated from contract: {len(grader_pairs)}")
    for grader, policy in grader_pairs:
        print(f"  {grader.grader_id:<28s} (policy={policy.value})")

    composite = CompositeGrader(
        grader_id="planner_contract",
        graders=[(g, 1.0) for g, _ in grader_pairs],
    )

    eval_set = EvalSet(name="planner-contract", tasks=[
        Task(name="travel plan", input_data={"goal": "Plan a weekend trip"}),
        Task(name="learning plan", input_data={"goal": "Learn Rust in 30 days"}),
    ])

    batch = await EvaluationRunner(
        SimpleAdapter(planner_agent), [composite], RunnerConfig(num_runs=2),
    ).run(eval_set)

    gen = ReportGenerator()
    print()
    print(gen.render_ci_summary(gen.build_report(batch)))


if __name__ == "__main__":
    asyncio.run(main())
